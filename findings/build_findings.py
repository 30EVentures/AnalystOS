"""Generates one page per finding plus an index, from findings/registry.json
(Slice 101).

    python3 findings/build_findings.py           # write findings/pages/
    python3 findings/build_findings.py --check    # exit 1 if stale, change nothing

Output lands in findings/pages/, not site/, until there is at least one real
(non-template) entry and the owner decides to publish - see findings/README.md
for exactly why, and what "publish" would mean once that decision is made.
Refuses to write anything if the registry does not validate.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
REGISTRY_PATH = ROOT / "registry.json"
OUTPUT_DIR = ROOT / "pages"

sys.path.insert(0, str(ROOT.parent))
from findings.validate import validate_registry  # noqa: E402


def _cell(value) -> str:
    """A markdown table cell is one line: a literal newline or a bare pipe
    would break the row, so both are neutralised. No HTML-entity escaping -
    this is markdown, not HTML, and schema.json already bounds what these
    fields may contain."""
    return str(value).replace("\n", " ").replace("|", "\\|")


def _page(entry: dict) -> str:
    fix = f"{entry['fix_commit_url']}" if entry.get("fix_commit_url") else "not yet fixed"
    note = f"\n**Note:** {entry['note']}\n" if entry.get("note") else ""
    return (
        f"# {entry['id']}: {entry['title']}\n\n"
        f"- **Status:** {entry['status']}\n"
        f"- **Severity (30E Ventures' own rating):** {entry['severity']}\n"
        f"- **Affected:** `{entry['affected']['package']}` at `{entry['affected']['version']}`\n"
        f"- **Discovered:** {entry['discovered']}\n"
        f"- **Published:** {entry.get('published')}\n"
        f"- **Reproducer exists:** {entry['reproducer_exists']} (held privately; not published here)\n"
        f"- **Fix:** {fix}\n\n"
        f"{entry['summary']}\n"
        f"{note}"
    )


def _index(registry: list) -> str:
    rows = "\n".join(
        f"| [{e['id']}]({e['id']}.md) | {_cell(e['title'])} | {e['status']} | {e['discovered']} |"
        for e in sorted(registry, key=lambda e: e["id"])
    )
    return (
        "# Findings index\n\n"
        "Generated by `findings/build_findings.py` from `registry.json`. Do not hand-edit.\n\n"
        "| Finding | Title | Status | Discovered |\n|---|---|---|---|\n" + rows + "\n"
    )


def build() -> dict:
    """Returns {relative_path: content} for every file this tool would
    write. Raises ValueError if the registry does not validate."""
    registry = json.loads(REGISTRY_PATH.read_text())
    problems = validate_registry(registry)
    if problems:
        raise ValueError(f"registry.json does not validate: {json.dumps(problems, indent=2)}")

    files = {f"{entry['id']}.md": _page(entry) for entry in registry}
    files["index.md"] = _index(registry)
    return files


def main(argv=None):
    args = sys.argv[1:] if argv is None else argv
    check = "--check" in args

    try:
        files = build()
    except ValueError as exc:
        print(f"build_findings.py: {exc}")
        return 1

    stale = []
    for name, content in files.items():
        path = OUTPUT_DIR / name
        if not path.exists() or path.read_text() != content:
            stale.append(name)

    extra = []
    if OUTPUT_DIR.is_dir():
        extra = [p.name for p in OUTPUT_DIR.glob("*.md") if p.name not in files]

    if check:
        if stale or extra:
            print(f"build_findings.py: STALE or extra files {stale + extra} - run without --check")
            return 1
        print(f"build_findings.py: {len(files)} page(s) match the registry")
        return 0

    OUTPUT_DIR.mkdir(exist_ok=True)
    for extra_name in extra:
        (OUTPUT_DIR / extra_name).unlink()
    for name, content in files.items():
        (OUTPUT_DIR / name).write_text(content)
    print(f"build_findings.py: wrote {len(files)} page(s) to {OUTPUT_DIR.relative_to(ROOT.parent)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
