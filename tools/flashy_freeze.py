def _sha(data):
    return hashlib.sha256(data).hexdigest()


def _canon(value):
    return json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=False).encode("utf-8")


def tracked_files(root):
    """Repo-relative POSIX paths of the repository's files, committed or about to be.

    In a checkout: tracked plus untracked-but-not-ignored files, so a violation is
    caught before ``git add``, not after. Outside a checkout (a copy, as the tests
    make): every file under the root."""
    root = Path(root)
    if (root / ".git").exists():
        out = subprocess.run(
            ["git", "ls-files", "-z", "--cached", "--others", "--exclude-standard"],
            cwd=root, capture_output=True, check=True,
        )
        names = {n for n in out.stdout.decode("utf-8").split("\0") if n}
        return sorted(n for n in names if (root / n).is_file() and not (set(n.split("/")) & SKIP_PARTS))
    found = []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [d for d in dirnames if d not in SKIP_PARTS]
        for name in filenames:
            found.append((Path(dirpath) / name).relative_to(root).as_posix())
    return sorted(found)


def _dir_files(rel, tracked, exclude=()):
    prefix = rel.rstrip("/") + "/"
    return sorted(p for p in tracked if p.startswith(prefix) and p not in exclude)


def _vercel_source_regex(source):
    """Approximate Vercel's path-to-regexp source syntax as a Python regex.

    Over-matching only pins more blocks (safe); the forms used here are literal
    paths, ``:name``, ``:name*``/``:name+`` and raw groups like ``(.*)``."""
    pattern = re.sub(r":[A-Za-z_]\w*\*", "(?:.*)", source)
    pattern = re.sub(r":[A-Za-z_]\w*\+", "(?:.+)", pattern)
    pattern = re.sub(r":[A-Za-z_]\w*\??", "(?:[^/]+)", pattern)
    pattern = pattern.replace(".", r"\.").replace(r"\.*", ".*").replace(r"\.+", ".+")
    try:
        return re.compile(pattern)
    except re.error:
        return None


def _vercel_block_pinned(source):
    if not isinstance(source, str):
        return True
    if source.startswith(API_V1_PREFIX):
        return True
    regex = _vercel_source_regex(source)
    if regex is None:
        return True  # cannot tell what it matches: pin it
    return any(regex.fullmatch(path) for path in SERVED_PATHS)


def _vercel_blocks(root):
    try:
        config = json.loads((Path(root) / "vercel.json").read_text(encoding="utf-8"))
        pinned = sorted(
            _sha(_canon({"kind": kind, "block": block}))
            for kind in VERCEL_KINDS
            for block in config.get(kind, [])
            if _vercel_block_pinned(block.get("source") if isinstance(block, dict) else None)
        )
    except (OSError, ValueError, AttributeError, TypeError):
        return UNREADABLE
    return pinned


def _llms_section(root):
    try:
        lines = (Path(root) / LLMS_FILE).read_text(encoding="utf-8").splitlines()
    except (OSError, UnicodeDecodeError):
        return UNREADABLE
    if lines.count(LLMS_HEADING) != 1:
        return f"{UNREADABLE}: expected exactly one '{LLMS_HEADING}' heading, found {lines.count(LLMS_HEADING)}"
    start = lines.index(LLMS_HEADING)
    end = next((i for i in range(start + 1, len(lines)) if lines[i].startswith("## ")), len(lines))
    return _sha("\n".join(lines[start:end]).strip().encode("utf-8"))


def _append_only(root, rel):
    try:
        doc = json.loads((Path(root) / rel).read_text(encoding="utf-8"))
        entries = doc.get("entries", [])
        if not isinstance(entries, list):
            raise TypeError("entries is not a list")
        header = {k: v for k, v in doc.items() if k not in APPEND_ONLY_FREE_KEYS}
        ids = [e.get("id") if isinstance(e, dict) else None for e in entries]
    except (OSError, ValueError, AttributeError, TypeError):
        return {"header": UNREADABLE, "entries": [], "duplicate_ids": []}
    seen, dupes = set(), set()
    for entry_id in ids:
        if entry_id in seen:
            dupes.add(str(entry_id))
        seen.add(entry_id)
    return {
        "header": _sha(_canon(header)),
        "entries": [_sha(_canon(entry)) for entry in entries],  # file order
        "duplicate_ids": sorted(dupes),
    }


def _is_subsequence(needle, haystack):
    it = iter(haystack)
    return all(any(h == n for h in it) for n in needle)


def _openapi_v1(root=ROOT):
    """The /api/v1 OpenAPI document, built from the code under ``root``."""
    root = Path(root).resolve()
    if root == ROOT:
        from analystos.api_v1.openapi import build_openapi

        return build_openapi()
    code = ("import json, sys; sys.path.insert(0, sys.argv[1]); "
            "from analystos.api_v1.openapi import build_openapi; print(json.dumps(build_openapi()))")
    done = subprocess.run([sys.executable, "-I", "-c", code, str(root)], capture_output=True, text=True)
    if done.returncode != 0:
        return UNREADABLE
    return json.loads(done.stdout)


def compute(root=ROOT, openapi=None):
    """Everything the fence pins, as it is now under ``root``.

    ``openapi`` is the v1 OpenAPI document; by default it is built from the code under ``root``."""
    root = Path(root)
    tracked = tracked_files(root)
    files = {}
    for rel in EXACT_FILES:
        path = root / rel
        files[rel] = _sha(path.read_bytes()) if path.is_file() else None
    dirs = {}
    for rel in EXACT_DIRS:
        members = _dir_files(rel, tracked, exclude=WATCHED)
        dirs[rel] = {m: _sha((root / m).read_bytes()) for m in members}
    return {
        "files": files,
        "dirs": dirs,
        "membership": {rel: _dir_files(rel, tracked) for rel in MEMBERSHIP_DIRS},
        "openapi_v1": _sha(_canon(openapi if openapi is not None else _openapi_v1(root))),
        "vercel_blocks": _vercel_blocks(root),
        "llms_section": _llms_section(root),
        "append_only": {rel: _append_only(root, rel) for rel in APPEND_ONLY},
        "watched": dict(sorted(WATCHED.items())),
    }


def _fenced_paths(state):
    fenced = set(p for p, h in state["files"].items() if h is not None)
    for members in state["dirs"].values():
        fenced.update(members)
    fenced.update(APPEND_ONLY)
    return fenced


def unfenced_mentions(root=ROOT, state=None):
    """Repository files outside tests/ and specs/ that mention FlashyOS or AAO but are
    neither fenced nor watched. Each one is an undecided coupling."""
    root = Path(root)
    state = state if state is not None else compute(root)
    covered = _fenced_paths(state) | set(WATCHED) | {MANIFEST_NAME}
    found = []
    for rel in tracked_files(root):
        if rel.split("/", 1)[0] in COVERAGE_EXCLUDED_TOPS or rel in covered:
            continue
        try:
            text = (root / rel).read_bytes().decode("utf-8", errors="replace")
        except OSError:
            found.append(rel)  # cannot read it, so cannot clear it
            continue
        if MENTION.search(text):
            found.append(rel)
    return found


def stale_watched(root=ROOT):
    """Watched entries that no longer exist or no longer mention FlashyOS/AAO.

    A warning, not drift: routine rewrites of these files are exactly what
    watching (rather than freezing) allows. Prune them at the next fence move."""
    root = Path(root)
    stale = []
    for rel in sorted(WATCHED):
        try:
            text = (root / rel).read_bytes().decode("utf-8", errors="replace")
        except OSError:
            stale.append(rel)
            continue
        if not MENTION.search(text):
            stale.append(rel)
    return stale


def _log_problems(pinned):
    log = pinned.get("log")
    if not isinstance(log, list) or not log:
        return ["manifest log is missing or empty; every fence move must be on record"]
    problems = []
    first = log[0]
    if not isinstance(first, dict) or FIRST_PIN_MARK not in str(first.get("reason", "")):
        problems.append(f"manifest log no longer starts with the {FIRST_PIN_MARK} first pin")
    for i, entry in enumerate(log):
        if not isinstance(entry, dict) or not str(entry.get("reason", "")).strip():
            problems.append(f"manifest log entry {i} has no reason")
    return problems


def drift(pinned, current, unfenced=()):
    """Human- and machine-readable list of every way ``current`` departs from ``pinned``.

    Empty means the fence holds. Never empty on a malformed manifest: a fence
    that cannot be read fails closed."""
    if not isinstance(pinned, dict) or pinned.get("format") != FORMAT:
        return [f"manifest is missing or not {FORMAT}; the fence cannot be checked"]
    for key in ("files", "dirs", "membership", "append_only", "watched"):
        if not isinstance(pinned.get(key), dict):
            return [f"manifest field {key!r} is missing or malformed; the fence cannot be checked"]
    problems = _log_problems(pinned)

    for rel, digest in current["files"].items():
        if digest != pinned["files"].get(rel, "<not pinned>"):
            problems.append(f"file changed: {rel}")
    for rel in sorted(set(pinned["files"]) - set(current["files"])):
        problems.append(f"file dropped from the fence: {rel}")

    for rel, members in current["dirs"].items():
        want = pinned["dirs"].get(rel)
        if not isinstance(want, dict):
            problems.append(f"directory not pinned: {rel}/")
            continue
        for m in sorted(set(want) - set(members)):
            problems.append(f"file removed: {m}")
        for m in sorted(set(members) - set(want)):
            problems.append(f"file added inside a fenced directory: {m}")
        for m in sorted(set(want) & set(members)):
            if want[m] != members[m]:
                problems.append(f"file changed: {m}")
    for rel in sorted(set(pinned["dirs"]) - set(current["dirs"])):
        problems.append(f"directory dropped from the fence: {rel}/")

    for rel, members in current["membership"].items():
        want = pinned["membership"].get(rel)
        if not isinstance(want, list):
            problems.append(f"directory membership not pinned: {rel}/")
            continue
        for m in sorted(set(members) - set(want)):
            problems.append(f"file added to {rel}/ (publishing a new document is a fence move): {m}")
        for m in sorted(set(want) - set(members)):
            problems.append(f"file removed from {rel}/: {m}")

    if current["openapi_v1"] != pinned.get("openapi_v1"):
        problems.append("the /api/v1 OpenAPI contract changed (put new routes in a new API version)")

    if current["vercel_blocks"] != pinned.get("vercel_blocks"):
        problems.append("vercel.json: a block serving a fenced path or /api/v1 was added, changed or removed")

    if current["llms_section"] != pinned.get("llms_section"):
        detail = current["llms_section"] if str(current["llms_section"]).startswith(UNREADABLE) else "changed"
        problems.append(f"{LLMS_FILE}: the '{LLMS_HEADING[3:]}' section {detail}")

    for rel, now in current["append_only"].items():
        want = pinned["append_only"].get(rel)
        if not isinstance(want, dict):
            problems.append(f"append-only record not pinned: {rel}")
            continue
        if now["header"] != want.get("header"):
            problems.append(f"{rel}: unreadable, or a top-level field other than {APPEND_ONLY_FREE_KEYS} changed")
        past = want.get("entries", [])
        missing = set(past) - set(now["entries"])
        if missing:
            problems.append(f"{rel}: {len(missing)} past entr{'y' if len(missing) == 1 else 'ies'} changed or removed")
        elif not _is_subsequence(past, now["entries"]):
            problems.append(f"{rel}: past entries were reordered")
        if now["duplicate_ids"]:
            problems.append(f"{rel}: duplicate entry ids {now['duplicate_ids']}")

    if current["watched"] != pinned["watched"]:
        problems.append("the watched list in tools/flashy_freeze.py changed")

    for rel in unfenced:
        problems.append(f"mentions FlashyOS/AAO but is neither fenced nor watched: {rel}")
    return problems


def load_manifest(root=ROOT):
    path = Path(root) / MANIFEST_NAME
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None


def check(root=ROOT, openapi=None):
    current = compute(root, openapi=openapi)
    return drift(load_manifest(root), current, unfenced_mentions(root, current))


def build_manifest(current, previous_log, reason, today, moved):
    log = list(previous_log) + [{"date": today, "reason": reason, "moved": list(moved)}]
    manifest = {
        "format": FORMAT,
        "description": (
            "The FlashyOS integration, frozen while AnalystOS is rebuilt around it "
            "(specs/slice-107/spec.md). Check: python3 tools/flashy_freeze.py --check. "
            "Move only on purpose: --update --reason \"<why>\"; every move, and what it moved, is logged below."
        ),
        "log": log,
    }
    manifest.update(copy.deepcopy(current))
    return manifest


def update(root, reason, today):
    """Re-pin the fence under ``root``. Returns (exit code, message)."""
    root = Path(root)
    reason = (reason or "").strip()
    if not reason:
        return 2, "--update needs a non-empty --reason: moving the fence is a decision, and it is logged."
    manifest_path = root / MANIFEST_NAME
    previous = load_manifest(root)
    if manifest_path.exists() and not isinstance(previous, dict):
        return 1, (f"Refusing to re-pin over an unreadable {MANIFEST_NAME}: that would silently "
                   "start a new log. Restore it from git first.")
    current = compute(root)
    unfenced = unfenced_mentions(root, current)
    if unfenced:
        return 1, ("Refusing to pin: these files mention FlashyOS/AAO but are neither fenced nor watched.\n"
                   "Add each to EXACT_FILES/EXACT_DIRS or to WATCHED (with a reason) in tools/flashy_freeze.py:\n"
                   + "\n".join(f"  - {rel}" for rel in unfenced))
    stale = stale_watched(root)
    if stale:
        return 1, ("Refusing to pin: drop these from WATCHED (missing or no longer mention FlashyOS/AAO): "
                   + ", ".join(stale))
    missing = [rel for rel, h in current["files"].items() if h is None]
    for name in ("vercel_blocks", "llms_section", "openapi_v1"):
        if str(current[name]).startswith(UNREADABLE):
            missing.append(name)
    missing += [rel for rel, a in current["append_only"].items() if a["header"] == UNREADABLE or a["duplicate_ids"]]
    if missing:
        return 1, "Refusing to pin something missing or unreadable: " + ", ".join(missing)
    if previous is None:
        moved = ["initial pin"]
    else:
        moved = [p for p in drift(previous, current) if not p.startswith("manifest log")] or ["nothing (re-pinned as is)"]
    manifest = build_manifest(current, (previous or {}).get("log", []), reason, today, moved)
    manifest_path.write_text(json.dumps(manifest, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    n = len(manifest["log"])
    return 0, f"Flashy fence re-pinned ({n} log entr{'y' if n == 1 else 'ies'})."


def main(argv=None, root=ROOT):
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true", help="exit 1 and list drift; change nothing")
    mode.add_argument("--update", action="store_true", help="re-pin the fence (needs --reason)")
    parser.add_argument("--reason", default="", help="why the integration is changing (logged)")
    args = parser.parse_args(argv)

    if args.check:
        problems = check(root)
        for rel in stale_watched(root):
            print(f"warning: watched file no longer mentions FlashyOS/AAO (drop it at the next fence move): {rel}")
        if problems:
            print("Flashy fence: DRIFT")
            for p in problems:
                print(f"  - {p}")
            print("If this change to the FlashyOS integration is intended, run:\n"
                  "  python3 tools/flashy_freeze.py --update --reason \"<why>\"")
            return 1
        print("Flashy fence: holds")
        return 0

    code, message = update(root, args.reason, datetime.date.today().isoformat())
    print(message, file=sys.stderr if code else sys.stdout)
    return code


if __name__ == "__main__":
    sys.exit(main())
