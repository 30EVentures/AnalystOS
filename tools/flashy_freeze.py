#!/usr/bin/env python3
"""The Flashy fence (Slice 107): freeze the FlashyOS integration while the rest
of AnalystOS is rebuilt around it.

    python3 tools/flashy_freeze.py --check                     # exit 1 and list drift
    python3 tools/flashy_freeze.py --update --reason "<why>"   # move the fence, on purpose

Deliberately NOT a step in tools/refresh.py: refresh regenerates things
automatically, and a fence that regenerates itself protects nothing. Moving it
needs a reason, which is appended to the manifest's log so a later reader (a
person or an agent) can see when and why the integration changed.

See specs/slice-107/spec.md for what is fenced and why.
"""

